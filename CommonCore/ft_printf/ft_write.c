#include "ft_printf.h"

int	ft_write(const char *s)
{
	int	c;

	c = 0;
	while (s[c] && s[c] != '%')
	{
		if (ft_putchar(s[c]) == -1)
			return (-1);
		c++;
	}
	return (c);
}
